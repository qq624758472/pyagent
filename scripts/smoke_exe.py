"""Exercise the built EXE from an isolated directory (including Python tasks).

    python scripts/smoke_exe.py
"""
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path


def inside():
    import ctypes
    assert ctypes.windll.kernel32.GetConsoleWindow() == 0, "worker allocated a console"
    from PyQt5.QtWidgets import QApplication
    from core.config import Config, CONFIG_FILE
    from core.log import LOG_FILE, setup_logging
    from core.runtime import DATA_ROOT, RESOURCE_ROOT
    from core.sessions import save_session, load_session
    from core.skills import discover
    from core.tools import _run_python
    from core.workspace import Workspace
    from ui.main_window import MainWindow

    assert DATA_ROOT == Path(sys.executable).parent
    assert RESOURCE_ROOT != DATA_ROOT
    assert (RESOURCE_ROOT / "icons" / "app.png").is_file()
    cfg = Config()
    cfg.save()
    assert CONFIG_FILE.parent == DATA_ROOT and CONFIG_FILE.is_file()
    setup_logging()
    assert LOG_FILE.is_file() and LOG_FILE.parent.parent == DATA_ROOT
    skills = {s.name for s in discover(cfg)}
    assert {"code-review", "report-writer"} <= skills, skills
    from core.tools import execute_tool
    skill_result = execute_tool("load_skill", None, cfg, {"name": "skill_report_writer"})
    assert "技能规范：report-writer" in skill_result and not skill_result.startswith("错误"), skill_result

    workspace = DATA_ROOT / "workspace"
    workspace.mkdir(exist_ok=True)
    from core.word_documents import inspect_docx
    word_ws = Workspace(workspace)
    word_ws.write_file("report.docx", "# Word report\n\nGenerated by the bundled application.\n")
    assert "Generated by the bundled application" in inspect_docx(workspace / "report.docx")["text"]
    assert "DOCX" in word_ws.read_file("report.docx")
    script = workspace / "hello.py"
    script.write_text("import csv, sqlite3, statistics, sys, ctypes\n"
                      "assert ctypes.windll.kernel32.GetConsoleWindow() == 0\n"
                      "print('BUNDLED_PYTHON_OK', statistics.mean([2,4]), sys.argv[1])\n"
                      "print('STDERR_OK', file=sys.stderr)\n",
                      encoding="utf-8")
    result = _run_python(Workspace(workspace), cfg, "hello.py", args="test-arg",
                         _confirmed=True)
    assert "BUNDLED_PYTHON_OK 3 test-arg" in result, result
    assert "STDERR_OK" in result, result
    from core.process_tools import _spawn, _tail
    proc, output = _spawn(Workspace(workspace), script, "test-arg")
    try:
        assert proc.wait(timeout=30) == 0
        assert "STDERR_OK" in _tail(output)
    finally:
        output.close()
    bad_script = workspace / "bad.py"
    bad_script.write_text("raise ValueError('EXPECTED_SCRIPT_ERROR')\n", encoding="utf-8")
    failure = _run_python(Workspace(workspace), cfg, "bad.py", _confirmed=True)
    assert "EXPECTED_SCRIPT_ERROR" in failure and "退出码 1" in failure, failure
    save_session("smoke", [{"role": "user", "content": "exe smoke test"}], "", "Smoke")
    assert load_session("smoke")["title"] == "Smoke"

    app = QApplication([])
    app.setStyle("Fusion")
    win = MainWindow(cfg)
    win.show()
    app.processEvents()
    assert not win.windowIcon().isNull()
    assert win.content_stack.currentIndex() == 1  # restores the isolated session
    win.new_chat()
    assert win.content_stack.currentIndex() == 0
    markdown = '## Result\n\n| Check | State |\n| --- | --- |\n| Tests | Passed |\n'
    win.on_event({'type': 'delta', 'content': markdown})
    view = win._stream_view
    win.on_event({'type': 'answer', 'content': markdown})
    assert view.source == markdown and view.toPlainText().count('Result') == 1
    from PyQt5.QtGui import QTextTable
    assert any(isinstance(f, QTextTable) for f in view.document().rootFrame().childFrames())
    # 验证打包后的网络事件泵：阻塞等待期间也能发送心跳。
    import time
    from core.llm_client import LLMClient
    request_client = LLMClient(Config(api_key="smoke"))
    request_client.REASONING_BEAT = 0.01
    def slow_request(payload, desc, timeout=None, cancelled=None):
        time.sleep(0.15)
        if not cancelled.is_set():
            yield "content", "NETWORK_PUMP_OK"
    request_client._read_sse = slow_request
    network_events = list(request_client.chat_turn([{"role": "user", "content": "test"}]))
    assert any(event["type"] == "keepalive" for event in network_events)
    assert any(event.get("text") == "NETWORK_PUMP_OK" for event in network_events)
    from ui.main_window import SettingsDialog
    settings = SettingsDialog(cfg, win)
    settings.e_llm_timeout.setValue(600)
    settings.c_llm_proxy.setCurrentIndex(1)
    network_values = settings.values()
    assert network_values['llm_read_timeout'] == 600
    assert network_values['llm_use_system_proxy'] is False
    direct_client = LLMClient(Config(api_key='smoke', llm_read_timeout=600, llm_use_system_proxy=False))
    assert direct_client._timeouts() == (10, 600)
    assert direct_client._route_label('http://example.invalid/v1') == '直连接口'
    settings.hide()
    from core.session_context import resume_task, normalize_messages
    assert 'SMOKE_RESUME_GOAL' in resume_task({'requests': ['SMOKE_RESUME_GOAL']}, 'workspace')
    assert normalize_messages([['user', 'continue']])[0]['content'] == 'continue'
    win.agent.restore_session({'messages': [['user', 'SMOKE_RESUME_GOAL']],
                               'continuity': {'requests': ['SMOKE_RESUME_GOAL'], 'results': []}})
    win._save_current_session()
    from core.sessions import load_session
    assert load_session(win._session_id)['continuity']['requests'] == ['SMOKE_RESUME_GOAL']
    win.agent.messages = [{'role': 'system', 'content': 's'}, {'role': 'user', 'content': 'first'},
                          {'role': 'user', 'content': 'RESUME_CURRENT'}] + [
                          {'role': 'assistant', 'content': 'x'*100} for _ in range(50)]
    win.agent.KEEP_CHARS = 5
    win.agent._trim_history()
    assert len(win.agent.messages) <= 4 and win.agent.messages[2]['content'] == 'RESUME_CURRENT'
    from core.llm_client import LLMStreamInterrupted
    win.agent._stream_recoveries = 0
    win.agent._task = 'SMOKE_RESUME_GOAL'
    assert win.agent._recover_interrupted_stream(LLMStreamInterrupted('smoke timeout'))
    assert win.agent._stream_recoveries == 1
    assert 'SMOKE_RESUME_GOAL' in win.agent.messages[-1]['content']
    from core.research_state import ResearchState
    research = ResearchState('编写 Word 技术方案')
    research.notes['source.c'] = 'void SourceMain(void);'
    research.drafting = True
    assert '本阶段暂不继续读取' in research.context()
    assert ResearchState('编写 Word 技术方案', research.snapshot()).drafting
    win.toggle_theme()
    assert cfg.theme == "light"
    win.hide()
    print(json.dumps({"result": "PASS", "skills": sorted(skills),
                      "checks": ["portable data", "resources", "logging", "skills",
                                 "no console", "bundled Python stdout/stderr",
                                 "background process output", "script errors",
                                 "sessions", "Qt GUI", "theme", "valid Word generation", "streaming Markdown tables",
                                 "network wait heartbeat", "skill tool-name alias", "model network settings", "session continuity", "interrupted stream recovery", "research stage persistence"]}))


def main():
    root = Path(__file__).resolve().parent.parent
    target = root / "build" / "exe smoke"
    target.mkdir(parents=True, exist_ok=True)
    exe = target / "PyAgent.exe"
    shutil.copy2(root / "dist" / "PyAgent.exe", exe)
    import pefile
    with pefile.PE(str(exe), fast_load=True) as pe:
        assert pe.OPTIONAL_HEADER.Subsystem == 2, "EXE must use Windows GUI subsystem"
    env = dict(os.environ, QT_QPA_PLATFORM="offscreen", PYTHONIOENCODING="utf-8")
    for key in list(env):
        if key.startswith("AGENT_"):
            del env[key]
    result = subprocess.run([str(exe), "--run-python", str(Path(__file__).resolve()), "--inside"],
                            cwd=str(target), env=env, capture_output=True,
                            text=True, encoding="utf-8", errors="replace", timeout=120,
                            creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0))
    print(result.stdout)
    if result.returncode:
        print(result.stderr)
        raise SystemExit(result.returncode)
    (root / "build" / "exe-smoke.json").write_text(result.stdout, encoding="utf-8")


if __name__ == "__main__":
    if "--inside" in sys.argv:
        inside()
    else:
        main()
